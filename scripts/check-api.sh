#!/bin/sh
set -eu
KOTOBA_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
KOTOBA_TOOLCHAIN=$(sh "$KOTOBA_ROOT/scripts/go.sh" env GOROOT)
KOTOBA_UNFORMATTED=$("$KOTOBA_TOOLCHAIN/bin/gofmt" -l "$KOTOBA_ROOT/cmd" "$KOTOBA_ROOT/internal")
if [ -n "$KOTOBA_UNFORMATTED" ]; then
  printf 'Run make api-fmt. Unformatted files:\n%s\n' "$KOTOBA_UNFORMATTED" >&2
  exit 1
fi
sh "$KOTOBA_ROOT/scripts/go.sh" build ./...
sh "$KOTOBA_ROOT/scripts/go.sh" vet ./...
sh "$KOTOBA_ROOT/scripts/go.sh" test -race ./...
sh "$KOTOBA_ROOT/scripts/go.sh" run honnef.co/go/tools/cmd/staticcheck@v0.8.1 ./...
sh "$KOTOBA_ROOT/scripts/go.sh" run golang.org/x/vuln/cmd/govulncheck@v1.8.0 ./...
